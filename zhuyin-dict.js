export function escapeHTML(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function parseZhuyinTokens(rawText) {
  const tokens = [];
  const regex = /([\u4e00-\u9fff])\(([^)]+)\)|([\u4e00-\u9fff])|([^\u4e00-\u9fff]+)/g;
  let m;
  while ((m = regex.exec(rawText)) !== null) {
    if (m[1] && m[2]) tokens.push({ type: 'ruby', char: m[1], bpmf: m[2].trim(), speak: m[1] });
    else if (m[3]) tokens.push({ type: 'ruby', char: m[3], bpmf: ZHUYIN_DICT[m[3]] || '', speak: m[3] });
    else if (m[4]) tokens.push({ type: 'plain', text: m[4], speak: m[4] });
  }
  return tokens;
}

export const getPlainSpeakText = (raw) => parseZhuyinTokens(raw).map(t => t.speak).join('');

export function renderZhuyinHTML(rawText) {
  return parseZhuyinTokens(rawText).map(t => {
    if (t.type === 'plain') return `<span class="plain-token">${escapeHTML(t.text)}</span>`;
    const bpmf = t.bpmf ? `<span class="bpmf">${escapeHTML(t.bpmf)}</span>` : '';
    return `<span class="char-ruby"><span class="hanzi">${escapeHTML(t.char)}</span>${bpmf}</span>`;
  }).join('');
}
